<#
  Writes infra\rdp-desktop.json: everything needed to rebuild the cloud desktop in another project,
  read live from Google Cloud. No secrets (no keys, passwords or Windows key material), so it is
  safe to commit. restore.ps1 reads it. backup.ps1 runs this automatically.
#>
. "$PSScriptRoot\settings.ps1"
$ErrorActionPreference = "Stop"

$inst = GJson compute instances describe $Vm --zone=$Zone --project=$Project
$diskName = ($inst.disks | Where-Object boot).source.Split("/")[-1]
$disk = GJson compute disks describe $diskName --zone=$Zone --project=$Project
$meta = @{}
foreach ($i in $inst.metadata.items) { $meta[$i.key] = $i.value }

$firewall = @(GJson compute firewall-rules list --project=$Project) |
  Where-Object { $_.targetTags -contains "rdp" -or $_.name -match "rdp" } |
  ForEach-Object {
    [ordered]@{
      name = $_.name; disabled = [bool]$_.disabled; sourceRanges = $_.sourceRanges; targetTags = $_.targetTags
      allow = @($_.allowed | ForEach-Object { if ($_.ports) { $p = $_.IPProtocol; $_.ports | ForEach-Object { "${p}:$_" } } else { $_.IPProtocol } })
    }
  }

$roles = [ordered]@{}
foreach ($r in "rdpControl", "rdpSelfSuspend") {
  $roles[$r] = @((GJson iam roles describe $r --project=$Project).includedPermissions)
}

$schedules = @($disk.resourcePolicies | Where-Object { $_ } | ForEach-Object {
    $p = GJson compute resource-policies describe $_.Split("/")[-1] --region=$Region --project=$Project
    [ordered]@{ name = $p.name; schedule = $p.snapshotSchedulePolicy }
  })

$blueprint = [ordered]@{
  note             = "Generated by ops/export-blueprint.ps1. Rebuild with ops/restore.ps1. No secrets in here."
  exportedAt       = (Get-Date).ToUniversalTime().ToString("s") + "Z"
  project          = $Project
  zone             = $Zone
  vm               = $Vm
  machineType      = $inst.machineType.Split("/")[-1]
  os               = "Windows Server 2022 Datacenter (Google on-demand license)"
  disk             = [ordered]@{
    name = $diskName; sizeGb = [int]$disk.sizeGb; type = $disk.type.Split("/")[-1]
    licenses = @($disk.licenses | ForEach-Object { $_ -replace '^https://www.googleapis.com/compute/v1/', '' })
    guestOsFeatures = @($disk.guestOsFeatures.type)
    snapshotSchedules = $schedules
  }
  tags             = @($inst.tags.items)
  serviceAccount   = [ordered]@{ email = $inst.serviceAccounts[0].email; scopes = $inst.serviceAccounts[0].scopes }
  rdpPort          = [int]($(if ($meta["rdp-port"]) { $meta["rdp-port"] } else { 3389 }))
  metadataFromRepo = [ordered]@{ "windows-startup-script-ps1" = "vm/startup.ps1"; "rdp-unlock-watcher" = "vm/unlock-watcher.ps1" }
  metadata         = [ordered]@{ "enable-guest-attributes" = $meta["enable-guest-attributes"]; "rdp-port" = $meta["rdp-port"] }
  firewall         = @($firewall)
  customRoles      = $roles
  website          = [ordered]@{
    url = "https://rdp-admin.vercel.app"
    serviceAccount = "rdp-website@$Project.iam.gserviceaccount.com"
    envNames = @("APP_PASSWORD", "SESSION_SECRET", "GCP_PROJECT_ID", "GCE_ZONE", "GCE_INSTANCE", "RDP_USERNAME", "RDP_PASSWORD", "GCP_SA_KEY_B64")
  }
}

New-Item -ItemType Directory -Force -Path (Split-Path $BlueprintPath) | Out-Null
[IO.File]::WriteAllText([IO.Path]::GetFullPath($BlueprintPath), ($blueprint | ConvertTo-Json -Depth 8))
Write-Host "Wrote $([IO.Path]::GetFullPath($BlueprintPath))"
